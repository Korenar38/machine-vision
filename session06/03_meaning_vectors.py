def words(s):
    """Слова фразы маленькими буквами, без знаков препинания."""
    for ch in ",.?!—«»":
        s = s.replace(ch, " ")
    return set(s.lower().split())


def search(query, base, base_vectors, k=3):
    scores = (embed(query) @ base_vectors.T)[0]
    best = scores.topk(k)
    print(f"\nЗапрос: «{query}»")
    for s, i in zip(best.values.tolist(), best.indices.tolist()):
        print(f"   {s:.2f}  {base[i]}")
    overlap = [len(words(query) & words(b)) for b in base]       # обычный поиск: число общих слов
    i = max(range(len(base)), key=lambda j: overlap[j])
    print("   поиск по словам:", base[i] if overlap[i] else "ничего не нашёл", f"(общих слов: {overlap[i]})")


